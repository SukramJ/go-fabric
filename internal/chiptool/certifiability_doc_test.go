// No build tag: this runs in every `go test ./...`. It needs no harness —
// only the family table and the golden file the last family run wrote.

var updateCertifiabilityDoc = flag.Bool("update-certifiability-doc", false,
	"rewrite the generated block of docs/certifiability.md from the family table and the golden file")

const (
	// chipCasesGoldenFile is the family run's golden file under testdata/.
	chipCasesGoldenFile = "chip-cases.golden.json"

	certDocPath  = "docs/certifiability.md"
	certDocBegin = "<!-- BEGIN GENERATED by internal/chiptool TestCertifiabilityDocument; do not edit -->"
	certDocEnd   = "<!-- END GENERATED -->"
)

// docGolden is the part of testdata/chip-cases.golden.json the document is
// built from.
type docGolden struct {
	Image         string                     `json:"image"`
	Cases         map[string]json.RawMessage `json:"cases"`
	Families      map[string][]string        `json:"families"`
	NotApplicable map[string]string          `json:"notApplicable"`
	HostSkipped   map[string]string          `json:"hostSkipped"`
}

// TestCertifiabilityDocument holds docs/certifiability.md's generated block
// to the family table (families_table_test.go) and the last family run
// (testdata/chip-cases.golden.json), and holds the run to ADR 0011: every
// case of every declared family either passed or is a classified gap.
func TestCertifiabilityDocument(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("testdata", chipCasesGoldenFile))
	if err != nil {
		t.Fatal(err)
	}
	var g docGolden
	if err := json.Unmarshal(data, &g); err != nil {
		t.Fatal(err)
	}

	var unclassified []string
	for _, fam := range chipFamilies {
		names, ok := g.Families[fam.name]
		if !ok {
			t.Errorf("family %s is declared but has never run: run `GOFABRIC_CHIP_FAMILIES=%s make chiptool-families` "+
				"with -update-chip-cases and commit the golden file", fam.name, fam.name)
			continue
		}
		for _, n := range names {
			if _, ex := fam.gapFor(n); ex {
				continue
			}
			if _, na := g.NotApplicable[fam.name+"/"+n]; na {
				continue
			}
			if _, hs := g.HostSkipped[fam.name+"/"+n]; hs {
				continue
			}
			if !passedIn(g, fam.name+"/"+n) {
				unclassified = append(unclassified, fam.name+"/"+n)
			}
		}
	}
	for _, id := range unclassified {
		t.Errorf("%s neither passed in the last run nor is a classified gap (ADR 0011): fix it, or add it to "+
			"the family's exclude with its class and reason", id)
	}

	block := renderCertifiability(g)
	root := filepath.Join("..", "..")
	file := filepath.Join(root, certDocPath)
	doc, err := os.ReadFile(file) //nolint:gosec // a fixed repository path
	if err != nil {
		t.Fatal(err)
	}
	text := string(doc)
	b, e := strings.Index(text, certDocBegin), strings.Index(text, certDocEnd)
	if b < 0 || e < b {
		t.Fatalf("%s lacks the generated-block markers", certDocPath)
	}
	updated := text[:b] + certDocBegin + "\n\n" + block + "\n" + text[e:]
	if updated == text {
		return
	}
	if *updateCertifiabilityDoc {
		if err := os.WriteFile(file, []byte(updated), 0o644); err != nil { //nolint:gosec // a committed document
			t.Fatal(err)
		}
		return
	}
	t.Errorf("%s's generated block is out of date with the family table or the golden file; "+
		"regenerate: go test ./internal/chiptool/ -run TestCertifiabilityDocument -args -update-certifiability-doc", certDocPath)
}

// gapFor returns the gap a case is, if it is excluded.
func (f family) gapFor(name string) (gap, bool) {
	keys := make([]string, 0, len(f.exclude))
	for k := range f.exclude {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, pattern := range keys {
		if ok, _ := path.Match(pattern, name); ok {
			return f.exclude[pattern], true
		}
	}
	return gap{}, false
}

// passedIn reports whether a case (or, for a per-endpoint case, every one
// of its endpoint runs) has golden counts.
func passedIn(g docGolden, id string) bool {
	if _, ok := g.Cases[id]; ok {
		return true
	}
	n := 0
	for k := range g.Cases {
		if strings.HasPrefix(k, id+"@") {
			n++
		}
	}
	return n > 0
}

func renderCertifiability(g docGolden) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Harness image: `%s`.\n\n", g.Image)
	b.WriteString("| Family | Cases | Passed | of which with a recorded gap | (a) defect | (b) not supported | (c) harness | (d) out of scope |\n")
	b.WriteString("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n")
	type row struct {
		gaps  []string
		known []string
	}
	rows := map[string]row{}
	tot := map[string]int{}
	for _, fam := range chipFamilies {
		names := g.Families[fam.name]
		counts := map[gapClass]int{}
		passed, known := 0, 0
		var r row
		for _, n := range names {
			id := fam.name + "/" + n
			if expr, na := g.NotApplicable[id]; na {
				if _, ex := fam.gapFor(n); !ex {
					counts[classNotSupported]++
					r.gaps = append(r.gaps, fmt.Sprintf("| %s | %s | not applicable: the case's PICS %s%s%s is false for the reference DUT |", id, classNotSupported, "`", mdCell(expr), "`"))
					continue
				}
			}
			if why, hs := g.HostSkipped[id]; hs {
				if _, ex := fam.gapFor(n); !ex {
					counts[classHarness]++
					r.gaps = append(r.gaps, fmt.Sprintf("| %s | %s | %s |", id, classHarness, mdCell(why)))
					continue
				}
			}
			if gp, ex := fam.gapFor(n); ex {
				counts[gp.class]++
				reason := gp.reason
				if gp.selfSkip {
					reason += " (runs, and skips itself)"
				}
				r.gaps = append(r.gaps, fmt.Sprintf("| %s | %s | %s |", id, gp.class, mdCell(reason)))
				continue
			}
			if passedIn(g, id) {
				passed++
				if kp, ok := fam.knownProblems[n]; ok {
					known++
					r.known = append(r.known, fmt.Sprintf("| %s | %s | %s |", id, kp.class, mdCell(kp.reason)))
				}
			}
		}
		rows[fam.name] = r
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d | %d | %d |\n", fam.name, len(names), passed, known,
			counts[classDefect], counts[classNotSupported], counts[classHarness], counts[classOutOfScope])
		tot["cases"] += len(names)
		tot["passed"] += passed
		tot["known"] += known
		for _, c := range []gapClass{classDefect, classNotSupported, classHarness, classOutOfScope} {
			tot[string(c)] += counts[c]
		}
	}
	fmt.Fprintf(&b, "| **all** | **%d** | **%d** | **%d** | **%d** | **%d** | **%d** | **%d** |\n\n", tot["cases"], tot["passed"], tot["known"],
		tot[string(classDefect)], tot[string(classNotSupported)], tot[string(classHarness)], tot[string(classOutOfScope)])

	b.WriteString("### Cases not run\n\n")
	b.WriteString("| Case | Class | Reason |\n| --- | --- | --- |\n")
	var all, knownAll []string
	for _, fam := range chipFamilies {
		all = append(all, rows[fam.name].gaps...)
		knownAll = append(knownAll, rows[fam.name].known...)
	}
	slices.Sort(all)
	for _, l := range all {
		b.WriteString(l + "\n")
	}
	b.WriteString("\n### Cases that pass with a recorded gap\n\n")
	b.WriteString("The CHIP checker reports exactly the recorded problems and nothing else; the case fails as soon as\n")
	b.WriteString("another problem appears or a recorded one disappears.\n\n")
	b.WriteString("| Case | Class | Gap |\n| --- | --- | --- |\n")
	slices.Sort(knownAll)
	for _, l := range knownAll {
		b.WriteString(l + "\n")
	}
	return b.String()
}

// mdCell escapes the pipes of a Markdown table cell.
func mdCell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

// TestWorkflowRunsEveryFamily holds the family groups of
// .github/workflows/chiptool.yml (chip-families matrix) to the family
// table: every declared family runs in exactly one group, and no group
// names a family the table does not declare.
func TestWorkflowRunsEveryFamily(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("..", "..", ".github", "workflows", "chiptool.yml"))
	if err != nil {
		t.Fatal(err)
	}
	// The groups are the `"<group>=<FAMILY,FAMILY,…>"` entries of the
	// `groups` step in the workflow's `code touched` job.
	entry := regexp.MustCompile(`^"([a-z-]+)=([A-Z0-9,]+)"$`)
	seen := map[string]int{}
	groups := 0
	for _, line := range strings.Split(string(data), "\n") {
		m := entry.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}
		groups++
		for _, f := range strings.Split(m[2], ",") {
			seen[f]++
		}
	}
	if groups == 0 {
		t.Fatal("no family groups found in chiptool.yml (expected `\"<group>=<families>\"` entries in the `groups` step)")
	}
	declared := map[string]bool{}
	for _, fam := range chipFamilies {
		declared[fam.name] = true
		if seen[fam.name] != 1 {
			t.Errorf("family %s runs in %d workflow groups, want exactly 1", fam.name, seen[fam.name])
		}
	}
	for f := range seen {
		if !declared[f] {
			t.Errorf("the workflow runs family %s, which families_table_test.go does not declare", f)
		}
	}
}
