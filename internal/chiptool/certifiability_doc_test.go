// No build tag: this runs in every `go test ./...`. It needs no harness —
// only the family table and the golden file the last family run wrote.

var updateCertifiabilityDoc = flag.Bool("update-certifiability-doc", false,
	"rewrite the generated block of docs/certifiability.md from the family table and the golden file")

const (
	// chipCasesGoldenFile is the family run's golden file under testdata/.
	chipCasesGoldenFile = "chip-cases.golden.json"

	certDocPath  = "docs/certifiability.md"
	certDocBegin = "<!-- BEGIN GENERATED by internal/chiptool TestCertifiabilityDocument; do not edit -->"
	certDocEnd   = "<!-- END GENERATED -->"
)

// docGolden is the part of testdata/chip-cases.golden.json the document is
// built from.
type docGolden struct {
	Image         string                     `json:"image"`
	Cases         map[string]json.RawMessage `json:"cases"`
	Families      map[string][]string        `json:"families"`
	NotApplicable map[string]string          `json:"notApplicable"`
	HostSkipped   map[string]string          `json:"hostSkipped"`
	GoCert        map[string]docGoCert       `json:"goCert"`
}

// docGoCert is a case of the Go-TH leg (gocert_test.go): its counts and the
// matter.js case file it mirrors.
type docGoCert struct {
	Steps        int      `json:"steps"`
	StepsSkipped int      `json:"stepsSkipped"`
	Source       string   `json:"source"`
	Findings     []string `json:"findings"`
	// Role is "dut" for a case run with the Go controller as the DUT.
	Role string `json:"role"`
}

// dut reports a case the Go controller runs as the DUT (phase 29b).
func (c docGoCert) dut() bool { return c.Role == "dut" }

// TestCertifiabilityDocument holds docs/certifiability.md's generated block
// to the family table (families_table_test.go) and the last family run
// (testdata/chip-cases.golden.json), and holds the run to ADR 0011: every
// case of every declared family either passed or is a classified gap.
func TestCertifiabilityDocument(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("testdata", chipCasesGoldenFile))
	if err != nil {
		t.Fatal(err)
	}
	var g docGolden
	if err := json.Unmarshal(data, &g); err != nil {
		t.Fatal(err)
	}

	var unclassified []string
	inFamily := map[string]bool{}
	for _, fam := range chipFamilies {
		for _, n := range g.Families[fam.name] {
			inFamily[fam.name+"/"+n] = true
		}
	}
	for id, c := range g.GoCert {
		// A DUT case may name a case no family of the image has (matter.js
		// automates controller cases CHIP's descriptor does not list): it is
		// listed under the controller role and counted in no family.
		if !inFamily[id] && !c.dut() {
			t.Errorf("Go-TH case %s is in no declared family's case list", id)
		}
		if _, hs := g.HostSkipped[id]; hs {
			t.Errorf("Go-TH case %s also has a host-skipped row: a case the leg runs is not one nobody automates", id)
		}
	}
	for _, fam := range chipFamilies {
		names, ok := g.Families[fam.name]
		if !ok {
			t.Errorf("family %s is declared but has never run: run `GOFABRIC_CHIP_FAMILIES=%s make chiptool-families` "+
				"with -update-chip-cases and commit the golden file", fam.name, fam.name)
			continue
		}
		for _, n := range names {
			if _, ex := fam.gapFor(n); ex {
				continue
			}
			if _, na := g.NotApplicable[fam.name+"/"+n]; na {
				continue
			}
			if _, hs := g.HostSkipped[fam.name+"/"+n]; hs {
				continue
			}
			if !passedIn(g, fam.name+"/"+n) {
				unclassified = append(unclassified, fam.name+"/"+n)
			}
		}
	}
	for _, id := range unclassified {
		t.Errorf("%s neither passed in the last run nor is a classified gap (ADR 0011): fix it, or add it to "+
			"the family's exclude with its class and reason", id)
	}

	block := renderCertifiability(g)
	root := filepath.Join("..", "..")
	file := filepath.Join(root, certDocPath)
	doc, err := os.ReadFile(file) //nolint:gosec // a fixed repository path
	if err != nil {
		t.Fatal(err)
	}
	text := string(doc)
	b, e := strings.Index(text, certDocBegin), strings.Index(text, certDocEnd)
	if b < 0 || e < b {
		t.Fatalf("%s lacks the generated-block markers", certDocPath)
	}
	updated := text[:b] + certDocBegin + "\n\n" + block + "\n" + text[e:]
	if updated == text {
		return
	}
	if *updateCertifiabilityDoc {
		if err := os.WriteFile(file, []byte(updated), 0o644); err != nil { //nolint:gosec // a committed document
			t.Fatal(err)
		}
		return
	}
	t.Errorf("%s's generated block is out of date with the family table or the golden file; "+
		"regenerate: go test ./internal/chiptool/ -run TestCertifiabilityDocument -args -update-certifiability-doc", certDocPath)
}

// gapFor returns the gap a case is, if it is excluded.
func (f family) gapFor(name string) (gap, bool) {
	keys := make([]string, 0, len(f.exclude))
	for k := range f.exclude {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, pattern := range keys {
		if ok, _ := path.Match(pattern, name); ok {
			return f.exclude[pattern], true
		}
	}
	return gap{}, false
}

// passedIn reports whether a case (or, for a per-endpoint case, every one
// of its endpoint runs) has golden counts.
func passedIn(g docGolden, id string) bool {
	if _, ok := g.Cases[id]; ok {
		return true
	}
	if _, ok := g.GoCert[id]; ok {
		return true
	}
	n := 0
	for k := range g.Cases {
		if strings.HasPrefix(k, id+"@") {
			n++
		}
	}
	return n > 0
}

func renderCertifiability(g docGolden) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Harness image: `%s`.\n\n", g.Image)
	b.WriteString("| Family | Cases | Passed | of which with a recorded gap | (a) defect | (b) not supported | (c) harness | (d) out of scope |\n")
	b.WriteString("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n")
	type row struct {
		gaps  []string
		known []string
	}
	rows := map[string]row{}
	tot := map[string]int{}
	for i := range chipFamilies {
		fam := &chipFamilies[i]
		names := g.Families[fam.name]
		counts := map[gapClass]int{}
		passed, known := 0, 0
		var r row
		for _, n := range names {
			id := fam.name + "/" + n
			// A case the Go controller passes as the DUT is passed in its
			// family: the page states the module in both roles (ADR 0020),
			// and the row the device role leaves (not applicable, manual)
			// is about the daemon, not about the case.
			if gc, ok := g.GoCert[id]; ok && gc.dut() {
				passed++
				if len(gc.Findings) > 0 {
					known++
					r.known = append(r.known, fmt.Sprintf("| %s | %s | Go controller as DUT: step %s (notes/parity/matter_behaviour_findings.md) |",
						id, classDefect, mdCell(strings.Join(gc.Findings, "; step "))))
				}
				continue
			}
			if expr, na := g.NotApplicable[id]; na {
				if _, ex := fam.gapFor(n); !ex {
					counts[classNotSupported]++
					why := ""
					if g, ok := controllerRoleCases[id]; ok {
						why = "; " + g.reason
					}
					r.gaps = append(r.gaps, fmt.Sprintf("| %s | %s | not applicable: the case's PICS %s%s%s is false for the reference DUT%s |", id, classNotSupported, "`", mdCell(expr), "`", mdCell(why)))
					continue
				}
			}
			if why, hs := g.HostSkipped[id]; hs {
				if _, ex := fam.gapFor(n); !ex {
					counts[classHarness]++
					r.gaps = append(r.gaps, fmt.Sprintf("| %s | %s | %s |", id, classHarness, mdCell(why)))
					continue
				}
			}
			if gp, ex := fam.gapFor(n); ex {
				counts[gp.class]++
				reason := gp.reason
				if gp.selfSkip {
					reason += " (runs, and skips itself)"
				}
				r.gaps = append(r.gaps, fmt.Sprintf("| %s | %s | %s |", id, gp.class, mdCell(reason)))
				continue
			}
			if passedIn(g, id) {
				passed++
				if kp, ok := fam.knownProblems[n]; ok {
					known++
					r.known = append(r.known, fmt.Sprintf("| %s | %s | %s |", id, kp.class, mdCell(kp.reason)))
				} else if gc, ok := g.GoCert[id]; ok && len(gc.Findings) > 0 {
					// A Go-TH case whose step fails with a recorded daemon
					// defect (gocert_test.go goStep.finding).
					known++
					r.known = append(r.known, fmt.Sprintf("| %s | %s | Go controller as TH: step %s (notes/parity/matter_behaviour_findings.md) |",
						id, classDefect, mdCell(strings.Join(gc.Findings, "; step "))))
				}
			}
		}
		rows[fam.name] = r
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d | %d | %d |\n", fam.name, len(names), passed, known,
			counts[classDefect], counts[classNotSupported], counts[classHarness], counts[classOutOfScope])
		tot["cases"] += len(names)
		tot["passed"] += passed
		tot["known"] += known
		for _, c := range []gapClass{classDefect, classNotSupported, classHarness, classOutOfScope} {
			tot[string(c)] += counts[c]
		}
	}
	fmt.Fprintf(&b, "| **all** | **%d** | **%d** | **%d** | **%d** | **%d** | **%d** | **%d** |\n\n", tot["cases"], tot["passed"], tot["known"],
		tot[string(classDefect)], tot[string(classNotSupported)], tot[string(classHarness)], tot[string(classOutOfScope)])

	b.WriteString("### Cases not run\n\n")
	b.WriteString("| Case | Class | Reason |\n| --- | --- | --- |\n")
	var all, knownAll []string
	for i := range chipFamilies {
		fam := &chipFamilies[i]
		all = append(all, rows[fam.name].gaps...)
		knownAll = append(knownAll, rows[fam.name].known...)
	}
	slices.Sort(all)
	for _, l := range all {
		b.WriteString(l + "\n")
	}
	b.WriteString("\n### Cases run with the Go controller as TH\n\n")
	b.WriteString("matter.js's certification cases for the controller side, read mirrored: the reference daemon is the DUT,\n")
	b.WriteString("the module's own controller performs the TS file's controller actions, and the TS file's TH-side\n")
	b.WriteString("expectations are what the daemon has to satisfy (`internal/chiptool` TestGoCertificationCases).\n\n")
	b.WriteString("| Case | Steps run | Steps skipped | Source |\n| --- | ---: | ---: | --- |\n")
	goIDs := make([]string, 0, len(g.GoCert))
	var dutIDs []string
	for id, c := range g.GoCert {
		if c.dut() {
			dutIDs = append(dutIDs, id)
			continue
		}
		goIDs = append(goIDs, id)
	}
	slices.Sort(goIDs)
	slices.Sort(dutIDs)
	for _, id := range goIDs {
		c := g.GoCert[id]
		also := ""
		if _, ok := g.Cases[id]; ok {
			also = "; passes with chip-tool as TH too"
		}
		fmt.Fprintf(&b, "| %s | %d | %d | Go controller as TH, after matter.js `%s`%s |\n", id, c.Steps, c.StepsSkipped, mdCell(c.Source), also)
	}
	b.WriteString("\n### Controller role\n\n")
	b.WriteString("matter.js's certification cases in their own direction: the module's controller is the DUT and the\n")
	b.WriteString("reference daemon the TH device the TS file names (`internal/chiptool` TestGoCertificationCases). Such a\n")
	b.WriteString("case counts as passed in its family; one no family of the harness image lists is counted in none.\n\n")
	b.WriteString("#### Cases run with the Go controller as DUT\n\n")
	b.WriteString("| Case | Steps run | Steps skipped | Source |\n| --- | ---: | ---: | --- |\n")
	for _, id := range dutIDs {
		c := g.GoCert[id]
		also := ""
		if _, ok := g.Cases[id]; ok {
			also = "; passes with chip-tool too"
		} else if !inFamilies(g, id) {
			also = "; in no family of the harness image"
		}
		fmt.Fprintf(&b, "| %s | %d | %d | Go controller as DUT, after matter.js `%s`%s |\n", id, c.Steps, c.StepsSkipped, mdCell(c.Source), also)
	}
	b.WriteString("\n#### Controller-role cases not run\n\n")
	b.WriteString("matter.js's cases with its controller as DUT that the Go controller does not run as the DUT and no family of\n")
	b.WriteString("the harness image lists; those a family lists carry the same reason on their row above.\n\n")
	b.WriteString("| Case | Class | Reason |\n| --- | --- | --- |\n")
	roleIDs := make([]string, 0, len(controllerRoleCases))
	for id := range controllerRoleCases {
		if _, run := g.GoCert[id]; !run && !inFamilies(g, id) {
			roleIDs = append(roleIDs, id)
		}
	}
	slices.Sort(roleIDs)
	for _, id := range roleIDs {
		gp := controllerRoleCases[id]
		fmt.Fprintf(&b, "| %s | %s | %s |\n", id, gp.class, mdCell(gp.reason))
	}
	b.WriteString("\n### Cases that pass with a recorded gap\n\n")
	b.WriteString("The CHIP checker reports exactly the recorded problems and nothing else; the case fails as soon as\n")
	b.WriteString("another problem appears or a recorded one disappears.\n\n")
	b.WriteString("| Case | Class | Gap |\n| --- | --- | --- |\n")
	slices.Sort(knownAll)
	for _, l := range knownAll {
		b.WriteString(l + "\n")
	}
	return b.String()
}

// inFamilies reports whether a case id is in the case list of a family
// of the last run.
func inFamilies(g docGolden, id string) bool {
	fam, name, _ := strings.Cut(id, "/")
	return slices.Contains(g.Families[fam], name)
}

// mdCell escapes the pipes of a Markdown table cell.
func mdCell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

// longRunningBudget is the case budget from which a family belongs in the
// workflow's `long` group: a case that waits for hours by design
// (TC-DGGEN-2.1, 3 h 10 min of literal waits) runs nightly and on
// dispatch, never on a pull request.
const longRunningBudget = time.Hour

// TestWorkflowRunsEveryFamily holds the family groups of
// .github/workflows/chiptool.yml (chip-families matrix) to the family
// table: every declared family runs in exactly one group, no group names
// a family the table does not declare, and the `long` group is exactly
// the families with a case budget of longRunningBudget or more.
func TestWorkflowRunsEveryFamily(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("..", "..", ".github", "workflows", "chiptool.yml"))
	if err != nil {
		t.Fatal(err)
	}
	// The groups are the `"<group>=<FAMILY,FAMILY,…>"` entries of the
	// `groups` step in the workflow's `code touched` job.
	entry := regexp.MustCompile(`^"([a-z-]+)=([A-Z0-9,]+)"$`)
	seen := map[string]int{}
	long := map[string]bool{}
	groups := 0
	for _, line := range strings.Split(string(data), "\n") {
		m := entry.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}
		groups++
		for _, f := range strings.Split(m[2], ",") {
			seen[f]++
			if m[1] == "long" {
				long[f] = true
			}
		}
	}
	if groups == 0 {
		t.Fatal("no family groups found in chiptool.yml (expected `\"<group>=<families>\"` entries in the `groups` step)")
	}
	declared := map[string]bool{}
	for _, fam := range chipFamilies {
		declared[fam.name] = true
		if seen[fam.name] != 1 {
			t.Errorf("family %s runs in %d workflow groups, want exactly 1", fam.name, seen[fam.name])
		}
		hours := false
		for _, d := range fam.timeout {
			hours = hours || d >= longRunningBudget
		}
		if hours != long[fam.name] {
			t.Errorf("family %s: a case budget of %s or more is %v, membership of the workflow's long group is %v; the two must agree", fam.name, longRunningBudget, hours, long[fam.name])
		}
	}
	for f := range seen {
		if !declared[f] {
			t.Errorf("the workflow runs family %s, which families_table_test.go does not declare", f)
		}
	}
}

// TestFamilyDeviceTypesResolve holds every endpoint the family table names
// — a row's deviceType and each per-case endpoints entry — to the device
// types the harness resolves (endpointDeviceTypes, pseudoEndpoints): an
// unresolved one fails every case it names with "no endpoint advertises
// device type", and only in the Linux CI run. A per-case entry must also
// name a case the family has in the last run's descriptor (the golden
// file), when the family has run.
func TestFamilyDeviceTypesResolve(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("testdata", chipCasesGoldenFile))
	if err != nil {
		t.Fatal(err)
	}
	var g docGolden
	if err := json.Unmarshal(data, &g); err != nil {
		t.Fatal(err)
	}
	resolves := func(dt uint32) bool {
		if dt == 0 || slices.Contains(endpointDeviceTypes, dt) {
			return true
		}
		at, ok := pseudoEndpoints[dt]
		return ok && slices.Contains(endpointDeviceTypes, at[0]) && slices.Contains(endpointDeviceTypes, at[1])
	}
	for _, fam := range chipFamilies {
		if !resolves(fam.deviceType) {
			t.Errorf("family %s runs on device type 0x%X, which the harness does not resolve (endpointDeviceTypes)", fam.name, fam.deviceType)
		}
		for c, dt := range fam.endpoints {
			if !resolves(dt) {
				t.Errorf("%s/%s runs on device type 0x%X, which the harness does not resolve (endpointDeviceTypes)", fam.name, c, dt)
			}
			if cases, ran := g.Families[fam.name]; ran && !slices.Contains(cases, c) {
				t.Errorf("%s/%s has an endpoints entry but the family has no such case in the image's descriptor (%v)", fam.name, c, cases)
			}
		}
	}
}
