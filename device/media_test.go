// built is v, or a panic for a construction the test's own fixture got
// wrong.
func built[T any](v T, err error) T {
	if err != nil {
		panic(err)
	}
	return v
}

// mediaServers builds the media package's servers the player types mount.
type mediaServers struct {
	playback *media.PlaybackServer
	keypad   *media.KeypadServer
	launcher *media.ContentLauncherServer
	apps     *media.AppLauncherServer
	inputs   *media.InputsServer
	outputs  *media.OutputsServer
}

func newMediaServers(t *testing.T) mediaServers {
	t.Helper()
	p := mediaPort{}
	return mediaServers{
		playback: built(media.NewPlayback(media.PlaybackConfig{Port: p})),
		keypad:   built(media.NewKeypad(media.KeypadConfig{Port: p})),
		launcher: built(media.NewContentLauncher(media.ContentLauncherConfig{Port: p, Features: launchdef.FeatureContentSearch | launchdef.FeatureUrlPlayback})),
		apps: built(media.NewAppLauncher(media.AppLauncherConfig{
			Port: p, Features: launcherdef.FeatureApplicationPlatform,
			Initial: media.AppLauncherState{CatalogList: []uint16{123}},
		})),
		inputs: built(media.NewInputs(media.InputsConfig{Port: p, Initial: media.InputState{
			InputList: []inputdef.InputInfoStruct{{Index: 1, InputType: inputdef.InputTypeHdmi, Name: "HDMI", Description: "HDMI 1"}},
		}})),
		outputs: built(media.NewOutputs(media.OutputsConfig{Port: p, Initial: media.OutputState{
			OutputList: []outputdef.OutputInfoStruct{{Index: 1, OutputType: outputdef.OutputTypeHdmi, Name: "HDMI"}},
		}})),
	}
}

// wantServers wants the device to serve exactly these instances.
func wantServers(t *testing.T, d *Device, servers ...contract.ClusterServer) {
	t.Helper()
	for _, srv := range servers {
		if got := d.Server(srv.MatterClusterID()); got != srv {
			t.Errorf("cluster 0x%04X: %T, want the media server %T", srv.MatterClusterID(), got, srv)
		}
	}
}

// TestMediaDeviceTypesMountTheMediaServers: each of the three media device
// types (generated by script/devicegen, ADR 0022) mounts the cluster/media
// servers the host supplies with WithServer — the generator types no
// default for them, as each needs the host's port (defaultFactories holds
// only port-less self-held servers) — states its conditions through
// Options.Conditions as the root states its own, and assembles without a
// device-type violation (endpoint.ValidateDeviceTypes, matter.js's
// DeviceTypeConformance).
func TestMediaDeviceTypesMountTheMediaServers(t *testing.T) {
	t.Parallel()
	t.Run("CastingVideoPlayer", func(t *testing.T) {
		t.Parallel()
		s := newMediaServers(t)
		opts := testOptions("casting")
		opts.Conditions = []string{"ContentAppPlatform", "PhysicalInputs"}
		d := built(NewCastingVideoPlayer(opts,
			withServer(s.playback), withServer(s.keypad), withServer(s.launcher),
			withServer(s.apps), withServer(s.inputs), withServer(s.outputs)))
		wantServers(t, d.Device, s.playback, s.keypad, s.launcher, s.apps, s.inputs, s.outputs)
		if _, ok := d.Server(0x0006).(*onoff.Server); !ok {
			t.Errorf("OnOff %T, want the default onoff.Server", d.Server(0x0006))
		}
		if v := violationsOf(assemble(t, d.Device)); len(v) != 0 {
			t.Errorf("violations %v", v)
		}
	})
	t.Run("CastingVideoPlayer condition without its cluster", func(t *testing.T) {
		t.Parallel()
		s := newMediaServers(t)
		opts := testOptions("casting-bare")
		opts.Conditions = []string{"ContentAppPlatform"}
		d := built(NewCastingVideoPlayer(opts, withServer(s.playback), withServer(s.keypad), withServer(s.launcher)))
		if v := violationsOf(assemble(t, d.Device)); len(v) == 0 {
			t.Error("ContentAppPlatform without ApplicationLauncher: no violation")
		}
	})
	t.Run("BasicVideoPlayer", func(t *testing.T) {
		t.Parallel()
		s := newMediaServers(t)
		opts := testOptions("basic")
		opts.Conditions = []string{"PhysicalInputs"}
		d := built(NewBasicVideoPlayer(opts, withServer(s.playback), withServer(s.keypad), withServer(s.inputs)))
		wantServers(t, d.Device, s.playback, s.keypad, s.inputs)
		if v := violationsOf(assemble(t, d.Device)); len(v) != 0 {
			t.Errorf("violations %v", v)
		}
	})
	t.Run("ContentApp", func(t *testing.T) {
		t.Parallel()
		p := mediaPort{}
		keypad := built(media.NewKeypad(media.KeypadConfig{Port: p}))
		apps := built(media.NewAppLauncher(media.AppLauncherConfig{Port: p}))
		basic := built(media.NewAppBasic(media.AppBasicConfig{Initial: media.AppBasicState{
			ApplicationName: "Example", Application: &basicdef.ApplicationStruct{CatalogVendorId: 123, ApplicationId: "exampleid"},
			ApplicationVersion: "1.0", AllowedVendorList: []uint16{},
		}}))
		opts := testOptions("app")
		opts.Conditions = []string{"ObserverClient"}
		d := built(NewContentApp(opts, withServer(keypad), withServer(apps), withServer(basic), WithClientClusters(0x0510)))
		wantServers(t, d.Device, keypad, apps, basic)
		if v := violationsOf(assemble(t, d.Device)); len(v) != 0 {
			t.Errorf("violations %v", v)
		}
	})
}
