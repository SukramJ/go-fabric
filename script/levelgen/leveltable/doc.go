package leveltable

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strings"
)

// Doc markers of docs/reference/spec-levels.md's generated block.
const (
	DocBegin = "<!-- BEGIN GENERATED by script/levelgen; do not edit -->"
	DocEnd   = "<!-- END GENERATED -->"
)

// Internal is one effective element of the reference daemon's composition
// at a level that the level does not know and no candidate decided: a
// hand-written server's own choice, which the level policy keeps with the
// reason "kept: server-internal, not level-controlled".
type Internal struct {
	Endpoint string
	Cluster  uint32
	// Kind is the surface kind's name: "cluster", "feature" (ID is the
	// one-bit mask), "attribute", "command" or "event".
	Kind string
	ID   uint32
}

// D9Cluster and D9Attribute are the hand exception of concept v11 §D.9:
// BridgedDeviceBasicInformation's ConfigurationVersion
// (cluster/spec/bridgeddevicebasicinformation AttrConfigurationVersion),
// which the level never removes.
const (
	D9Cluster   uint32 = 0x0039
	D9Attribute uint32 = 0x0018
)

// Doc renders the generated block (markers included): the level table,
// per level the device types and clusters it does not know and the
// elements kept because the pin mandates them, the hand exception, and
// per level the server-internal elements of the reference daemon.
func Doc(files []File, pin Pin, internal map[string][]Internal) []byte {
	var b bytes.Buffer
	b.WriteString(DocBegin + "\n\n")
	b.WriteString("## The levels\n\n")
	b.WriteString("| Level | matter.js tag | Commit | Method | Device types | Clusters | Features | Attributes | Commands | Events |\n")
	b.WriteString("| --- | --- | --- | --- | --: | --: | --: | --: | --: | --: |\n")
	for _, f := range files {
		var feat, attr, cmd, ev int
		for _, c := range f.Clusters {
			feat += len(c.Features)
			attr += len(c.Attributes)
			cmd += len(c.Commands)
			ev += len(c.Events)
		}
		fmt.Fprintf(&b, "| `%s` | `%s` | `%s` | %s | %d | %d | %d | %d | %d | %d |\n",
			f.Matter.Revision, f.Matter.Tag, short(f.Matter.SourceCommit), f.Matter.Method,
			len(f.DeviceTypes), len(f.Clusters), feat, attr, cmd, ev)
	}
	b.WriteString("\nThe last level is the pin's revision. Commands count each id once, request and response alike.\n\n")

	last := files[len(files)-1]
	pinCl := map[uint32]*Cluster{}
	for i := range last.Clusters {
		pinCl[last.Clusters[i].ID] = &last.Clusters[i]
	}
	b.WriteString("## What each level does not know\n\n")
	b.WriteString("Computed from the level files. A device whose type, or a cluster its type mandates, is\n")
	b.WriteString("absent at the level is **withheld**; an optional cluster, feature, attribute, command or\n")
	b.WriteString("event absent at the level is **removed**, unless the pin mandates it. *Kept, mandatory at\n")
	b.WriteString("the pin* lists the attributes, commands and events whose own conformance at the pin is\n")
	b.WriteString("unconditionally mandatory (`M`, or `Rev >= vN` at the cluster's revision) and that the\n")
	b.WriteString("level does not know, on clusters it knows; a composition also keeps what a device type\n")
	b.WriteString("or the feature selection mandates, which only the composition can tell.\n\n")
	for _, f := range files[:len(files)-1] {
		fmt.Fprintf(&b, "### Level %s\n\n", f.Matter.Revision)
		dts := map[uint32]bool{}
		for _, d := range f.DeviceTypes {
			dts[d.ID] = true
		}
		var absentDT []string
		for _, d := range last.DeviceTypes {
			if !dts[d.ID] {
				absentDT = append(absentDT, fmt.Sprintf("%s `0x%04X`", pin.DeviceTypeNames[d.ID], d.ID))
			}
		}
		fmt.Fprintf(&b, "Device types it does not know (%d): %s.\n\n", len(absentDT), listOrNone(absentDT))
		cls := map[uint32]*Cluster{}
		for i := range f.Clusters {
			cls[f.Clusters[i].ID] = &f.Clusters[i]
		}
		var absentCl []string
		for _, c := range last.Clusters {
			if cls[c.ID] == nil {
				absentCl = append(absentCl, fmt.Sprintf("%s `0x%04X`", pin.ClusterNames[c.ID], c.ID))
			}
		}
		fmt.Fprintf(&b, "Clusters it does not know (%d): %s.\n\n", len(absentCl), listOrNone(absentCl))
		var rows []string
		for _, pc := range last.Clusters {
			c := cls[pc.ID]
			if c == nil {
				continue
			}
			var cells []string
			for _, k := range []struct {
				kind      string
				pin, have []uint32
			}{
				{"attribute", pc.Mandatory.Attributes, c.Attributes},
				{"command", pc.Mandatory.Commands, c.Commands},
				{"event", pc.Mandatory.Events, c.Events},
			} {
				var ids []string
				for _, id := range k.pin {
					if !slices.Contains(k.have, id) {
						ids = append(ids, fmt.Sprintf("`0x%04X`", id))
					}
				}
				if len(ids) > 0 {
					cells = append(cells, k.kind+" "+strings.Join(ids, ", "))
				}
			}
			if len(cells) > 0 {
				rows = append(rows, fmt.Sprintf("| %s `0x%04X` | %s |", pin.ClusterNames[pc.ID], pc.ID, strings.Join(cells, "; ")))
			}
		}
		if len(rows) == 0 {
			b.WriteString("Kept, mandatory at the pin: none.\n\n")
		} else {
			b.WriteString("Kept, mandatory at the pin:\n\n| Cluster | Elements |\n| --- | --- |\n")
			b.WriteString(strings.Join(rows, "\n") + "\n\n")
		}
	}

	b.WriteString("## The hand exception (concept v11 D.9)\n\n")
	b.WriteString("| Cluster | Element | Rule |\n| --- | --- | --- |\n")
	fmt.Fprintf(&b, "| %s `0x%04X` | attribute ConfigurationVersion `0x%04X` | never removed by the level: \"kept: surface-change signal (concept v11 D.9)\" |\n\n",
		pin.ClusterNames[D9Cluster], D9Cluster, D9Attribute)

	b.WriteString("## Server-internal elements the level does not control\n\n")
	b.WriteString("A hand-written server chooses some optional elements itself; the level cannot remove\n")
	b.WriteString("them yet and keeps them with the reason \"kept: server-internal, not level-controlled\".\n")
	b.WriteString("Measured on the reference daemon's composition (`examples/reference-bridge\n")
	b.WriteString("--dump-surface --spec-level <level>`), with the endpoints that serve each.\n\n")
	for _, f := range files[:len(files)-1] {
		fmt.Fprintf(&b, "### Level %s\n\n", f.Matter.Revision)
		rows := internalRows(internal[f.Matter.Revision], pin)
		if len(rows) == 0 {
			b.WriteString("None.\n\n")
			continue
		}
		b.WriteString("| Cluster | Element | Endpoints |\n| --- | --- | --- |\n")
		b.WriteString(strings.Join(rows, "\n") + "\n\n")
	}
	b.WriteString(DocEnd + "\n")
	return b.Bytes()
}

// internalRows groups the server-internal elements by cluster, kind and
// id, listing the endpoints.
func internalRows(in []Internal, pin Pin) []string {
	type key struct {
		cluster uint32
		kind    string
		id      uint32
	}
	eps := map[key][]string{}
	for _, x := range in {
		k := key{x.Cluster, x.Kind, x.ID}
		if !slices.Contains(eps[k], x.Endpoint) {
			eps[k] = append(eps[k], x.Endpoint)
		}
	}
	keys := make([]key, 0, len(eps))
	for k := range eps {
		keys = append(keys, k)
	}
	slices.SortFunc(keys, func(a, b key) int {
		if a.cluster != b.cluster {
			return int(int64(a.cluster) - int64(b.cluster))
		}
		if a.kind != b.kind {
			return strings.Compare(a.kind, b.kind)
		}
		return int(int64(a.id) - int64(b.id))
	})
	out := make([]string, 0, len(keys))
	for _, k := range keys {
		names := eps[k]
		slices.Sort(names)
		for i, n := range names {
			if n == "" {
				names[i] = "(root)"
			} else {
				names[i] = "`" + n + "`"
			}
		}
		width := 4
		if k.kind != "cluster" {
			width = 8
		}
		out = append(out, fmt.Sprintf("| %s `0x%04X` | %s `0x%0*X` | %s |", pin.ClusterNames[k.cluster], k.cluster, k.kind, width, k.id, strings.Join(names, ", ")))
	}
	return out
}

func listOrNone(items []string) string {
	if len(items) == 0 {
		return "none"
	}
	return strings.Join(items, ", ")
}

// Splice replaces the generated block of doc with block; it fails when
// the markers are missing.
func Splice(doc, block []byte) ([]byte, error) {
	i := bytes.Index(doc, []byte(DocBegin))
	j := bytes.Index(doc, []byte(DocEnd))
	if i < 0 || j < i {
		return nil, fmt.Errorf("the generated block's markers are missing")
	}
	end := j + len(DocEnd)
	if end < len(doc) && doc[end] == '\n' {
		end++
	}
	out := append([]byte{}, doc[:i]...)
	out = append(out, block...)
	return append(out, doc[end:]...), nil
}

// Block returns doc's generated block, markers included.
func Block(doc []byte) ([]byte, bool) {
	i := bytes.Index(doc, []byte(DocBegin))
	j := bytes.Index(doc, []byte(DocEnd))
	if i < 0 || j < i {
		return nil, false
	}
	return doc[i : j+len(DocEnd)+1], true
}

func formatSource(src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("gofmt levels_gen.go: %w", err)
	}
	return out, nil
}
