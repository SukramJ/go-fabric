const (
	// referenceDir and referenceFile name the generated reference page of
	// the device types, published with the documentation site.
	referenceDir  = "docs/reference"
	referenceFile = "device-types.md"
	specImport    = "github.com/SukramJ/go-fabric/cluster/spec/"
)

// typeVar is the unexported variable holding a device type's requirement
// literal; the exported <Name>Type refers to it, so go doc prints one line
// per type instead of the literal.
func typeVar(n string) string { return "type" + n }

// referenceLink is the reference page's section of a device type, as the
// doc comment of its Type names it.
func referenceLink(name string) string {
	return referenceDir + "/" + referenceFile + "#" + strings.ToLower(name)
}

// typedPackages are the committed cluster definitions' packages, sorted.
func (g *generator) typedPackages() []string {
	pkgs := make([]string, 0, len(g.defs))
	for p := range g.defs {
		pkgs = append(pkgs, p)
	}
	slices.Sort(pkgs)
	return pkgs
}

// packageDocProse is the hand-written part of the device package's doc;
// generatePackageDoc appends the two generated lists below it.
const packageDocProse = `// Package device is the device layer: one Go type per Matter device type in
// scope, generated from parity/schema.json by script/devicegen, and the
// hand-written runtime they share — matter.js's packages/node/src/devices
// and packages/node/src/endpoints (ADR 0018).
//
// # Declaring a device
//
// A device type's constructor ([NewDimmableLight], …) mounts every server
// cluster the type mandates, each with its default server: the module's
// own where it has one, else the generated [spec.Server] with the features
// the type mandates and the defaults it states. The host states the rest
// in one declaration per cluster, the Declare of the cluster's typed
// package (onoffdef.Declare, …): the initial state, the feature selection,
// the write veto, the command handlers, the host port the module's server
// runs on, or the host's own server (HostServer) — as a matter.js host
// sets state and overrides a behavior. Declaring an optional cluster
// mounts it. [WithServer] mounts the host's own server for a cluster
// without a typed package. [FromSpec] builds the same device from data.
//
// A device's typed accessors (DimmableLight.OnOff, …) wrap the server the
// device mounts for the cluster, whatever its type (Underlying returns it),
// and read and set its state; OnChanged sees every change with its origin
// ([contract.Change]), OnChangedAsync runs on the device's own goroutine.
// Once the device is added to a node, [Device.SetReachable],
// [Device.Rename] and [Device.EndpointNumber] are its lifecycle.
//
// [Device.Spec] hands the device to the endpoint assembler as an
// [endpoint.Spec], so endpoint-id persistence and device-type validation
// are the assembler's (ADR 0016). The clusters the assembler mounts on
// every endpoint — Descriptor, Identify, BridgedDeviceBasicInformation,
// Groups and ScenesManagement — are never mounted here; an optional Groups
// or ScenesManagement is opted into with its declaration (groupsdef.Declare{},
// scenesmanagementdef.Declare{}) and mounted by the assembler.
//
// The package is public API from its first commit (README.md §API
// stability). A device type matter.js renames becomes an alias with a
// deprecation, not a break.
`

// generatePackageDoc renders device/doc_gen.go: the package doc, with the
// typed cluster packages by import path and the device types by name, so
// neither list drifts from what is generated.
func (g *generator) generatePackageDoc(names []string) (*output, error) {
	var w bytes.Buffer
	w.WriteString("// SPDX-License-Identifier: Apache-2.0\n// Copyright (C) 2026 SukramJ.\n\n")
	w.WriteString("// Code generated by script/devicegen from parity/schema.json. DO NOT EDIT.\n\n")
	w.WriteString(packageDocProse)
	w.WriteString("//\n// # Typed cluster packages\n//\n")
	w.WriteString("// Every cluster with a generated definition has a typed package — its\n")
	w.WriteString("// Declare, State, Patch and Server. The package at\n")
	w.WriteString("// github.com/SukramJ/go-fabric/cluster/spec/<pkg> is imported as <pkg>def\n")
	w.WriteString("// (onoffdef for .../cluster/spec/onoff):\n//\n")
	for _, p := range g.typedPackages() {
		fmt.Fprintf(&w, "//   - %s%s\n", specImport, p)
	}
	w.WriteString("//\n// # Device types\n//\n")
	fmt.Fprintf(&w, "// The cluster requirements of each are in %s/%s.\n//\n", referenceDir, referenceFile)
	for _, name := range names {
		dt := g.snap.deviceType(name)
		if dt == nil || dt.ID == nil {
			return nil, fmt.Errorf("no device type %s with an id in the snapshot", name)
		}
		fmt.Fprintf(&w, "//   - [%s] (0x%04X)\n", exportName(name), *dt.ID)
	}
	w.WriteString("package device\n")
	out, err := format.Source(w.Bytes())
	if err != nil {
		return nil, err
	}
	return &output{File: "doc_gen.go", Source: out}, nil
}

// generateReference renders docs/reference/device-types.md: each committed
// device type's identity and the cluster requirements its Type carries.
func (g *generator) generateReference(names []string) (*output, error) {
	var w bytes.Buffer
	w.WriteString("<!-- Code generated by script/devicegen from parity/schema.json. DO NOT EDIT. -->\n\n")
	w.WriteString("# Device types\n\n")
	fmt.Fprintf(&w, "The %d device types of the `device` package, from the matter.js model at\n", len(names))
	fmt.Fprintf(&w, "`%s` (Matter %s). Each section is what the type's `device.<Name>Type`\n", shortCommit(g.snap.Matter.SourceCommit), g.snap.Matter.Revision)
	w.WriteString("carries: the server and client clusters matter.js's generator derives,\n")
	w.WriteString("whether the type mandates each, the features it requires and the\n")
	w.WriteString("attributes, commands and events it alters. A cluster with a typed package\n")
	w.WriteString("is declared with that package's `Declare`.\n\n")
	w.WriteString("`script/devicegen` writes this page; a test fails when it is stale.\n\n")
	for _, name := range names {
		m, err := g.model(name)
		if err != nil {
			return nil, err
		}
		dt := m.dt
		fmt.Fprintf(&w, "## %s\n\n", name)
		fmt.Fprintf(&w, "`device.New%s` · id `0x%04X` · revision %d · %s · matter.js `%s`",
			exportName(name), *dt.ID, dt.Revision, dt.Classification, matterjsPath(dt))
		if dt.Effective.Base != "" {
			fmt.Fprintf(&w, " · base %s", dt.Effective.Base)
		}
		w.WriteString("\n\n")
		if len(dt.Effective.Conditions) > 0 {
			fmt.Fprintf(&w, "Conditions: %s.\n\n", strings.Join(dt.Effective.Conditions, ", "))
		}
		for _, side := range []struct {
			title  string
			reqs   []*clusterReq
			server bool
		}{{"Server cluster", m.servers, true}, {"Client cluster", m.clients, false}} {
			if len(side.reqs) == 0 {
				continue
			}
			if side.server {
				fmt.Fprintf(&w, "| %s | ID | Conformance | Required | Features | Elements | Declaration |\n", side.title)
				w.WriteString("| --- | --- | --- | --- | --- | --- | --- |\n")
			} else {
				fmt.Fprintf(&w, "| %s | ID | Conformance | Required |\n", side.title)
				w.WriteString("| --- | --- | --- | --- |\n")
			}
			for _, cr := range side.reqs {
				g.writeReferenceRow(&w, cr, side.server)
			}
			w.WriteString("\n")
		}
	}
	src := append(bytes.TrimRight(w.Bytes(), "\n"), '\n')
	return &output{File: referenceFile, Source: src}, nil
}

// writeReferenceRow is one requirement of the reference page, the facts
// writeRequirement puts into the Type literal.
func (g *generator) writeReferenceRow(w *bytes.Buffer, cr *clusterReq, server bool) {
	c := cr.def
	required := "optional"
	switch {
	case cr.mandatory:
		required = "mandatory"
	case cr.baseMandated:
		required = "mandatory (base)"
	}
	conf := cr.req.Conformance.text()
	if conf == "" {
		conf = "—"
	} else {
		conf = "`" + strings.ReplaceAll(conf, "|", `\|`) + "`"
	}
	fmt.Fprintf(w, "| %s | `0x%04X` | %s | %s", c.Name, c.ID, conf, required)
	if !server {
		w.WriteString(" |\n")
		return
	}
	features := make([]string, 0, len(cr.features))
	for _, f := range cr.features {
		if t := f.Effective.Title; t != "" {
			features = append(features, t+" ("+f.Name+")")
		} else {
			features = append(features, f.Name)
		}
	}
	elements := make([]string, 0, len(cr.elements))
	for _, e := range cr.elements {
		var facts []string
		switch e.presence {
		case "PresenceMandatory":
			facts = append(facts, "mandatory")
		case "PresenceOptional":
			facts = append(facts, "optional")
		}
		if e.hasMin && e.hasMax && e.min == e.max {
			facts = append(facts, "= "+num(e.min))
		} else {
			if e.hasDefault {
				facts = append(facts, "default "+num(e.def))
			}
			if e.hasMin {
				facts = append(facts, "min "+num(e.min))
			}
			if e.hasMax {
				facts = append(facts, "max "+num(e.max))
			}
		}
		elements = append(elements, fmt.Sprintf("%s %s (%s)", e.kind, e.name, strings.Join(facts, ", ")))
	}
	decl := "—"
	if pkg := packageName(c.Name); g.defs[pkg] {
		decl = "`" + pkg + "def.Declare`"
	}
	fmt.Fprintf(w, " | %s | %s | %s |\n", dash(strings.Join(features, ", ")), dash(strings.Join(elements, "; ")), decl)
}

// dash is s, or an em dash for an empty table cell.
func dash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}
