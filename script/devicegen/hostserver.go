package main

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
)

// generateHostServers renders device/hostserver_gen.go: the table
// device.HostServer resolves a server's cluster id through, one line per
// committed cluster definition under cluster/spec — its Declare with the
// host's server as HostServer. A cluster of the snapshot without a
// committed package has no line; HostServer mounts its server as
// WithServer does.
func (g *generator) generateHostServers() (*output, error) {
	type entry struct {
		id  uint32
		pkg string
	}
	var entries []entry
	seen := map[string]uint32{}
	for _, c := range g.snap.Clusters {
		pkg := packageName(c.Name)
		if !g.defs[pkg] {
			continue
		}
		if prev, ok := seen[pkg]; ok {
			return nil, fmt.Errorf("clusters 0x%04X and 0x%04X share the package %s", prev, c.ID, pkg)
		}
		seen[pkg] = c.ID
		entries = append(entries, entry{c.ID, pkg})
	}
	if len(entries) != len(g.defs) {
		return nil, fmt.Errorf("%d committed cluster packages, %d of them a snapshot cluster's", len(g.defs), len(entries))
	}
	slices.SortFunc(entries, func(a, b entry) int { return int(a.id) - int(b.id) })
	var w bytes.Buffer
	w.WriteString("// SPDX-License-Identifier: Apache-2.0\n// Copyright (C) 2026 SukramJ.\n\n")
	w.WriteString("// Code generated by script/devicegen from parity/schema.json. DO NOT EDIT.\n\n")
	w.WriteString("package device\n\nimport (\n")
	w.WriteString("\t\"github.com/SukramJ/go-fabric/contract\"\n")
	sorted := slices.Clone(entries)
	slices.SortFunc(sorted, func(a, b entry) int {
		switch {
		case a.pkg < b.pkg:
			return -1
		case a.pkg > b.pkg:
			return 1
		}
		return 0
	})
	for _, e := range sorted {
		fmt.Fprintf(&w, "\t%sdef \"github.com/SukramJ/go-fabric/cluster/spec/%s\"\n", e.pkg, e.pkg)
	}
	w.WriteString(")\n\n")
	w.WriteString("// hostServers resolves a cluster id to its generated declaration with\n")
	w.WriteString("// the host's server as HostServer ([HostServer]), one entry per\n")
	w.WriteString("// generated cluster package.\n")
	w.WriteString("var hostServers = map[uint32]func(contract.ClusterServer) Declaration{\n")
	for _, e := range entries {
		fmt.Fprintf(&w, "\t%[1]sdef.ClusterID: func(s contract.ClusterServer) Declaration { return %[1]sdef.Declare{HostServer: s} },\n", e.pkg)
	}
	w.WriteString("}\n")
	out, err := format.Source(w.Bytes())
	if err != nil {
		return nil, err
	}
	return &output{File: "hostserver_gen.go", Source: out}, nil
}
