// renderPage renders src's page. The register must have passed validate and
// check against snap.
func renderPage(src *source, snap *Snapshot, reg *Register) []byte {
	byPath := make(map[string]SnapshotFile, len(snap.Files))
	for i := range snap.Files {
		byPath[snap.Files[i].Path] = snap.Files[i]
	}
	dirs, perDir := groupByDir(reg.Entries)
	counts := reg.count()

	var b bytes.Buffer
	b.WriteString("<!-- Generated by `go run ./script/testparity -render` (make testparity) from\n")
	fmt.Fprintf(&b, "     %s and %s.\n", src.registerFile, src.snapshotFile)
	b.WriteString("     Do not edit: change the register and regenerate. -->\n\n")
	fmt.Fprintf(&b, "# %s tests: the porting register\n\n", src.name)
	b.WriteString(src.intro(snap))
	b.WriteString("`ported`: the Go tests cover the file's `it` cases; `partial`: they cover some, the note names the rest;\n")
	b.WriteString("`planned`: not ported yet; `excluded`: left out, with its class. A `ported` or `partial` note's \"Left\"\n")
	b.WriteString("names the `it` cases that will not be ported, each with its class and reason. The guard is `make testparity-check`.\n\n")

	b.WriteString("| status | files |\n| --- | ---: |\n")
	for _, s := range statuses {
		fmt.Fprintf(&b, "| %s | %d |\n", s, counts[s])
	}
	fmt.Fprintf(&b, "| total | %d |\n\n", len(reg.Entries))

	b.WriteString("## Per directory\n\n")
	b.WriteString("| directory | files | ported | partial | planned | excluded |\n| --- | ---: | ---: | ---: | ---: | ---: |\n")
	for _, d := range dirs {
		n := map[Status]int{}
		for _, e := range perDir[d] {
			n[e.Status]++
		}
		fmt.Fprintf(&b, "| [%s](#%s) | %d | %d | %d | %d | %d |\n", displayDir(d), anchor(displayDir(d)),
			len(perDir[d]), n[StatusPorted], n[StatusPartial], n[StatusPlanned], n[StatusExcluded])
	}
	b.WriteString("\n")

	for _, d := range dirs {
		fmt.Fprintf(&b, "## %s\n\n", displayDir(d))
		b.WriteString("| file | lines | status | Go tests or class | note |\n| --- | ---: | --- | --- | --- |\n")
		for _, e := range perDir[d] {
			fmt.Fprintf(&b, "| %s | %d | %s | %s | %s |\n",
				cell(path.Base(e.Path)), byPath[e.Path].Lines, e.Status, goOrClass(e), cell(note(e)))
		}
		b.WriteString("\n")
	}

	if src.skips {
		renderSkips(&b, reg)
	}
	renderPlanned(&b, dirs, perDir, counts[StatusPlanned])
	return append(bytes.TrimRight(b.Bytes(), "\n"), '\n')
}

// matterjsIntro is the matter.js page's paragraph before the counts.
func matterjsIntro(snap *Snapshot) string {
	var b strings.Builder
	fmt.Fprintf(&b, "matter.js pin `%s` (`parity/schema.json` → `matter.sourceCommit`): %d test files under %s.\n",
		snap.Commit, len(snap.Files), joinCode(snap.Roots))
	b.WriteString("Out of the roots, each for its reason: `packages/matter.js` (the umbrella package and its legacy controller API,\n")
	b.WriteString("MatterController and PairedNode, whose behaviour the protocol and node roots hold), `packages/nodejs-ws` (a WebSocket\n")
	b.WriteString("transport the module does not have), `packages/testing` (matter.js's test harness) and `support/codegen` (its TypeScript\n")
	b.WriteString("tooling). `packages/nodejs-ble/test` is in the roots since phase 39: its channel's BTP renegotiation is ported.\n")
	return b.String()
}

