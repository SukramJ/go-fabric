// renderPage writes notes/parity/matterjs_tests.md. The register must have
// passed validate and check against snap.
func renderPage(snap *Snapshot, reg *Register) []byte {
	byPath := make(map[string]SnapshotFile, len(snap.Files))
	for i := range snap.Files {
		byPath[snap.Files[i].Path] = snap.Files[i]
	}
	dirs, perDir := groupByDir(reg.Entries)
	counts := reg.count()

	var b bytes.Buffer
	b.WriteString("<!-- Generated by `go run ./script/testparity -render` (make testparity) from\n")
	b.WriteString("     script/testparity/register.json and script/testparity/matterjs_tests.json.\n")
	b.WriteString("     Do not edit: change the register and regenerate. -->\n\n")
	b.WriteString("# matter.js tests: the porting register\n\n")
	fmt.Fprintf(&b, "matter.js pin `%s` (`parity/schema.json` → `matter.sourceCommit`): %d test files under %s.\n",
		snap.Commit, len(snap.Files), joinCode(snap.Roots))
	b.WriteString("`ported`: the Go tests cover the file's `it` cases; `partial`: they cover some, the note names the rest;\n")
	b.WriteString("`planned`: not ported yet; `excluded`: left out, with its class. The guard is `make testparity-check`.\n\n")

	b.WriteString("| status | files |\n| --- | ---: |\n")
	for _, s := range statuses {
		fmt.Fprintf(&b, "| %s | %d |\n", s, counts[s])
	}
	fmt.Fprintf(&b, "| total | %d |\n\n", len(reg.Entries))

	b.WriteString("## Per directory\n\n")
	b.WriteString("| directory | files | ported | partial | planned | excluded |\n| --- | ---: | ---: | ---: | ---: | ---: |\n")
	for _, d := range dirs {
		n := map[Status]int{}
		for _, e := range perDir[d] {
			n[e.Status]++
		}
		fmt.Fprintf(&b, "| [%s](#%s) | %d | %d | %d | %d | %d |\n", displayDir(d), anchor(displayDir(d)),
			len(perDir[d]), n[StatusPorted], n[StatusPartial], n[StatusPlanned], n[StatusExcluded])
	}
	b.WriteString("\n")

	for _, d := range dirs {
		fmt.Fprintf(&b, "## %s\n\n", displayDir(d))
		b.WriteString("| file | lines | status | Go tests or class | note |\n| --- | ---: | --- | --- | --- |\n")
		for _, e := range perDir[d] {
			fmt.Fprintf(&b, "| %s | %d | %s | %s | %s |\n",
				cell(path.Base(e.Path)), byPath[e.Path].Lines, e.Status, goOrClass(e), cell(note(e)))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Planned\n\n")
	if counts[StatusPlanned] == 0 {
		b.WriteString("None.\n")
	}
	for _, d := range dirs {
		var planned []*Entry
		for _, e := range perDir[d] {
			if e.Status == StatusPlanned {
				planned = append(planned, e)
			}
		}
		if len(planned) == 0 {
			continue
		}
		fmt.Fprintf(&b, "### %s\n\n", displayDir(d))
		for _, e := range planned {
			fmt.Fprintf(&b, "- `%s` — %s\n", path.Base(e.Path), oneLine(e.Reason))
		}
		b.WriteString("\n")
	}
	return append(bytes.TrimRight(b.Bytes(), "\n"), '\n')
}

// groupByDir returns the entries' directories in tree order (segment by
// segment, so a directory precedes its subdirectories) and the entries of
// each, in register (path) order.
func groupByDir(entries []Entry) (dirs []string, perDir map[string][]*Entry) {
	perDir = map[string][]*Entry{}
	for i := range entries {
		d := path.Dir(entries[i].Path)
		perDir[d] = append(perDir[d], &entries[i])
	}
	dirs = make([]string, 0, len(perDir))
	for d := range perDir {
		dirs = append(dirs, d)
	}
	sort.Slice(dirs, func(i, j int) bool { return treeLess(dirs[i], dirs[j]) })
	return dirs, perDir
}

func treeLess(a, b string) bool {
	as, bs := strings.Split(a, "/"), strings.Split(b, "/")
	for i := 0; i < len(as) && i < len(bs); i++ {
		if as[i] != bs[i] {
			return as[i] < bs[i]
		}
	}
	return len(as) < len(bs)
}

// displayDir drops the "packages/" every snapshot path starts with.
func displayDir(d string) string { return strings.TrimPrefix(d, "packages/") }

// anchor is the heading id GitHub and mkdocs both derive for a heading made
// of lower-case path segments: slashes dropped.
func anchor(heading string) string {
	return strings.ReplaceAll(strings.ToLower(heading), "/", "")
}

func goOrClass(e *Entry) string {
	switch e.Status {
	case StatusPorted, StatusPartial:
		refs := make([]string, len(e.Go))
		for i, r := range e.Go {
			refs[i] = "`" + r + "`"
		}
		return strings.Join(refs, "<br>")
	case StatusExcluded:
		if e.Until != "" {
			return "`" + e.Class + "` until " + cell(e.Until)
		}
		return "`" + e.Class + "`"
	default:
		return "—"
	}
}

func note(e *Entry) string {
	s := oneLine(e.Reason)
	if len(e.Missing) > 0 {
		quoted := make([]string, len(e.Missing))
		for i, m := range e.Missing {
			quoted[i] = "“" + oneLine(m) + "”"
		}
		s += " Missing: " + strings.Join(quoted, "; ") + "."
	}
	return s
}

func joinCode(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = "`" + s + "`"
	}
	return strings.Join(q, " and ")
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// cell escapes what would end a table cell.
func cell(s string) string { return strings.ReplaceAll(oneLine(s), "|", `\|`) }
