// renderSkips writes the FixMe skips section.
func renderSkips(b *bytes.Buffer, reg *Register) {
	b.WriteString("## FixMe skips\n\n")
	b.WriteString("Go tests whose body is an unconditional `t.Skip(\"FixMe: …\")`: each names a case it would mirror and\n")
	b.WriteString("does not test. They count as passes in `go test`; this list is where they are recorded.\n\n")
	if len(reg.Skips) == 0 {
		b.WriteString("None.\n\n")
	} else {
		b.WriteString("| Go test | mirrors | why it skips |\n| --- | --- | --- |\n")
		for _, s := range reg.Skips {
			fmt.Fprintf(b, "| `%s` | %s | %s |\n", s.Test, cell(s.Source), cell(s.Reason))
		}
		b.WriteString("\n")
	}
}

// renderPlanned writes the planned section.
func renderPlanned(b *bytes.Buffer, dirs []string, perDir map[string][]*Entry, count int) {
	b.WriteString("## Planned\n\n")
	if count == 0 {
		b.WriteString("None.\n")
	}
	for _, d := range dirs {
		var planned []*Entry
		for _, e := range perDir[d] {
			if e.Status == StatusPlanned {
				planned = append(planned, e)
			}
		}
		if len(planned) == 0 {
			continue
		}
		fmt.Fprintf(b, "### %s\n\n", displayDir(d))
		for _, e := range planned {
			fmt.Fprintf(b, "- `%s` — %s\n", path.Base(e.Path), oneLine(e.Reason))
		}
		b.WriteString("\n")
	}
}

// groupByDir returns the entries' directories in tree order (segment by
// segment, so a directory precedes its subdirectories) and the entries of
// each, in register (path) order.
func groupByDir(entries []Entry) (dirs []string, perDir map[string][]*Entry) {
	perDir = map[string][]*Entry{}
	for i := range entries {
		d := path.Dir(entries[i].Path)
		perDir[d] = append(perDir[d], &entries[i])
	}
	dirs = make([]string, 0, len(perDir))
	for d := range perDir {
		dirs = append(dirs, d)
	}
	sort.Slice(dirs, func(i, j int) bool { return treeLess(dirs[i], dirs[j]) })
	return dirs, perDir
}

func treeLess(a, b string) bool {
	as, bs := strings.Split(a, "/"), strings.Split(b, "/")
	for i := 0; i < len(as) && i < len(bs); i++ {
		if as[i] != bs[i] {
			return as[i] < bs[i]
		}
	}
	return len(as) < len(bs)
}

// displayDir drops the "packages/" every snapshot path starts with.
func displayDir(d string) string { return strings.TrimPrefix(d, "packages/") }

// anchor is the heading id GitHub and mkdocs both derive for a heading made
// of lower-case path segments: slashes dropped.
func anchor(heading string) string {
	return strings.ReplaceAll(strings.ToLower(heading), "/", "")
}

func goOrClass(e *Entry) string {
	switch e.Status {
	case StatusPorted, StatusPartial:
		refs := make([]string, len(e.Go))
		for i, r := range e.Go {
			refs[i] = "`" + r + "`"
		}
		return strings.Join(refs, "<br>")
	case StatusExcluded:
		if e.Until != "" {
			return "`" + e.Class + "` until " + cell(e.Until)
		}
		return "`" + e.Class + "`"
	default:
		if e.Until != "" {
			return "until " + cell(e.Until)
		}
		return "—"
	}
}

func note(e *Entry) string {
	s := oneLine(e.Reason)
	if len(e.Missing) > 0 {
		quoted := make([]string, len(e.Missing))
		for i, m := range e.Missing {
			quoted[i] = "“" + oneLine(m) + "”"
		}
		s += " Missing: " + strings.Join(quoted, "; ") + "."
	}
	if len(e.Left) > 0 {
		left := make([]string, len(e.Left))
		for i, l := range e.Left {
			left[i] = "“" + oneLine(l.It) + "” (" + l.Class + ": " + oneLine(l.Reason) + ")"
		}
		s += " Left: " + strings.Join(left, "; ") + "."
	}
	return s
}

func joinCode(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = "`" + s + "`"
	}
	return strings.Join(q, " and ")
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// cell escapes what would end a table cell.
func cell(s string) string { return strings.ReplaceAll(oneLine(s), "|", `\|`) }
